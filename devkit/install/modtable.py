"""modtable — the MODULE.md body-section reader and the README module-table renderer.

Standard library only, on purpose: it reads the module sections from each `MODULE.md` and renders
the module table in `devkit/README.md`, so the installer and the tests share one piece of code.
"""
import re

BEGIN = "<!-- devkit:modules:begin -->"
END = "<!-- devkit:modules:end -->"
_FENCE_RE = re.compile(r"^\s{0,3}(`{3,}|~{3,})")


def extract_sections(body):
    """Text of each `## <Heading>` section of a MODULE.md body, keyed by heading.

    Lines inside a fenced code block (``` or ~~~) never start or end a section."""
    out = {}
    cur = None
    fence = None
    for line in body.splitlines():
        fm = _FENCE_RE.match(line)
        if fm:
            mark = fm.group(1)
            if fence is None:
                fence = mark[0] * 3
            elif mark[0] == fence[0] and len(mark) >= 3 and line.strip().strip(mark[0]) == "":
                fence = None
            if cur is not None:
                out[cur].append(line)
            continue
        if fence is None:
            m = re.match(r"##\s+(.+?)\s*$", line)
            if m:
                cur = m.group(1)
                out.setdefault(cur, [])
                continue
            if re.match(r"#\s", line):
                cur = None
                continue
        if cur is not None:
            out[cur].append(line)
    return {k: "\n".join(v).strip() for k, v in out.items()}


def render_module_table(rows):
    """rows: [{name, version, domain, mechanisms: [..], prevents}] -> the marked table block."""
    def cell(text):
        return " ".join(str(text).split()).replace("|", "\\|")

    lines = ["| Module | Version | Domain | Mechanisms | Prevents |", "|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: r["name"]):
        mechs = sorted(set(m for m in r.get("mechanisms", []) if m))
        lines.append("| %s | %s | %s | %s | %s |" % (
            cell(r["name"]), cell(r.get("version", "")), cell(r.get("domain", "")),
            cell(", ".join(mechs)), cell(r.get("prevents", ""))))
    return "\n".join([BEGIN,
                      "<!-- generated by `python3 devkit/install/_devkit.py readme`; edit a MODULE.md, not this table -->",
                      *lines, END])


def replace_table(text, rows):
    """`text` with the marked block replaced by the table for `rows`, or None when no markers."""
    b, e = text.find(BEGIN), text.find(END)
    if b < 0 or e < b:
        return None
    return text[:b] + render_module_table(rows) + text[e + len(END):]
